export function splitProjects(list: Project[], maxDestaques = 6): { destaques: Project[]; outros: Project[] } {
  const destaques: Project[] = []
  const outros: Project[] = []
  for (const p of list) {
    if (p.destaque && destaques.length < maxDestaques) destaques.push(p)
    else outros.push(p)
  }
  return { destaques, outros }
}
